assert.match(dispatcher,/method in setOf\("vortex\.agent", "riftos\.agent", "riftllm\.dev"\) -> agentExecutor/);
assert.match(bridge,/TARGET_REPO="Arctic403\/RiftLLM"/);
assert.match(bridge,/TARGET_BRANCH="main"/);
assert.match(bridge,/native\("list_benchmarks"/);
assert.match(bridge,/native\("get_benchmark"/);
