assert.match(manifest,/<package android:name="com\.riftllm\.app"\s*\/>/);
assert.match(client,/AUTHORITY = "com\.riftllm\.app\.devlab"/);
assert.match(client,/Uri\.parse\("content:\/\/\$AUTHORITY"\)/);
assert.match(client,/TOKEN_KEY = "riftllm\.dev\.token"/);
assert.match(client,/RiftSecretStore\(appContext\)/);
